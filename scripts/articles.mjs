export function getHostedArticleRoutes() {
  return ARTICLE_PAGES.map((article) => `/articulos/${article.slug}/`);
}

export function findHostedArticleByPathname(pathname) {
  return ARTICLE_PAGES.find((article) => pathname === `/articulos/${article.slug}/`) || null;
}

